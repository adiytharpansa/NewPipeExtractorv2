package org.schabi.newpipe.extractor.universal;

import javax.annotation.Nullable;
import java.io.Serializable;

/**
 * A subtitle track of a {@link UnifiedMedia}, in a service-agnostic form.
 */
public final class UnifiedSubtitle implements Serializable {
    private static final long serialVersionUID = 1L;

    @Nullable
    private final String url;
    @Nullable
    private final String languageTag;
    @Nullable
    private final String displayName;
    @Nullable
    private final String extension;
    private final boolean autoGenerated;

    /**
     * Creates a new subtitle track.
     *
     * @param url the direct URL of the subtitle file
     * @param languageTag the language tag of the track, e.g. {@code "en"}
     * @param displayName the display name of the language of the track
     * @param extension the file extension of the track format, e.g. {@code "vtt"}
     * @param autoGenerated whether the track was generated automatically by the service
     */
    public UnifiedSubtitle(@Nullable final String url,
                             @Nullable final String languageTag,
                             @Nullable final String displayName,
                             @Nullable final String extension,
                             final boolean autoGenerated) {
        this.url = url;
        this.languageTag = languageTag;
        this.displayName = displayName;
        this.extension = extension;
        this.autoGenerated = autoGenerated;
    }

    /**
     * Gets the direct URL of the subtitle file.
     *
     * @return the subtitle URL, or {@code null} if not available
     */
    @Nullable
    public String getUrl() {
        return url;
    }

    /**
     * Gets the language tag of the track.
     *
     * @return the language tag, or {@code null} if unknown
     */
    @Nullable
    public String getLanguageTag() {
        return languageTag;
    }

    /**
     * Gets the display name of the language of the track.
     *
     * @return the display name, or {@code null} if unknown
     */
    @Nullable
    public String getDisplayName() {
        return displayName;
    }

    /**
     * Gets the file extension of the track format.
     *
     * @return the extension, or {@code null} if unknown
     */
    @Nullable
    public String getExtension() {
        return extension;
    }

    /**
     * Checks whether the track was generated automatically by the service.
     *
     * @return {@code true} if the track is auto-generated, {@code false} otherwise
     */
    public boolean isAutoGenerated() {
        return autoGenerated;
    }
}
